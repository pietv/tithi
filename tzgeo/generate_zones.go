//go:build ignore

package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strconv"
	"strings"
	"text/template"
)

var tmpl = template.Must(template.New("zones").Parse(`// This file is automatically generated by ‘generate_zones.go’; DO NOT EDIT!

package tzgeo

var zones = map[string]Zone{
{{- range $i, $z := .}}
  {{printf "%q" $z.Name}}: {
    Name: {{printf "%q" $z.Name}},
    Lat: {{$z.Lat}},
    Lon: {{$z.Lon}},
    Countries: {{printf "%#v" $z.Countries}},
    Comments: {{printf "%q" $z.Comments}},
    Order: {{$i}},
  },
{{- end}}
}
`))

func main() {
	if err := generate(); err != nil {
		fmt.Fprintf(os.Stderr, "generate_zones: %v\n", err)
		os.Exit(1)
	}
}

type zone struct {
	Name      string
	Lat, Lon  float64
	Countries []string
	Comments  string
}

func generate() error {
	data, err := os.ReadFile("zone1970.tab")
	if err != nil {
		return err
	}

	var zones []zone
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for lineNo := 1; scanner.Scan(); lineNo++ {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || (len(line) > 0 && line[0] == '#') {
			continue
		}
		fields := strings.SplitN(line, "\t", 4)
		if len(fields) < 3 {
			return fmt.Errorf("scanner: line %d malformed: %q", lineNo, line)
		}
		lat, lon, err := parseISO6709(fields[1])
		if err != nil {
			return fmt.Errorf("scanner: line %d: %v", lineNo, err)
		}
		z := zone{
			Name:      fields[2],
			Lat:       lat,
			Lon:       lon,
			Countries: strings.Split(fields[0], ","),
		}
		if len(fields) == 4 {
			z.Comments = fields[3]
		}
		zones = append(zones, z)
	}
	if err := scanner.Err(); err != nil {
		return fmt.Errorf("scanner: reading tab file: %v", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, zones); err != nil {
		return err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format.source: %v", err)
	}
	if err := os.WriteFile("zones.go", src, 0644); err != nil {
		return err
	}
	fmt.Printf("Wrote zones.go (%d zones)\n", len(zones))
	return nil
}

// parseISO6709 converts a zone1970.tab coordinate pair to decimal degrees.
func parseISO6709(s string) (lat, lon float64, err error) {
	// The regexp matches the two coordinate shapes zone1970.tab uses — ±DDMM±DDDMM
	// and ±DDMMSS±DDDMMSS (ISO 6709 degrees and minutes, with optional seconds) —
	// capturing sign+degrees, minutes, and seconds ("" when absent) for each of
	// latitude and longitude.
	m := regexp.MustCompile(`^([+-]\d{2})(\d{2})(\d{2})?([+-]\d{3})(\d{2})(\d{2})?$`).FindStringSubmatch(s)
	if m == nil {
		return 0, 0, fmt.Errorf("cannot parse ISO 6709 coord %q", s)
	}
	return dms(m[1], m[2], m[3]), dms(m[4], m[5], m[6]), nil
}

// dms converts sign-prefixed degrees, minutes, and optional seconds to
// decimal degrees.
func dms(deg, min, sec string) float64 {
	d, _ := strconv.Atoi(deg[1:])
	m, _ := strconv.Atoi(min)
	s := 0
	if sec != "" {
		s, _ = strconv.Atoi(sec)
	}
	v := float64(d) + float64(m)/60 + float64(s)/3600
	if deg[0] == '-' {
		v = -v
	}
	return v
}
